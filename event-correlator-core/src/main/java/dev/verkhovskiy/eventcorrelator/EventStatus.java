package dev.verkhovskiy.eventcorrelator;

/** Durable-статус входящего события. */
public enum EventStatus {
  /** Событие принято, но еще не классифицировано. */
  RECEIVED,

  /** Событие ожидает недостающие зависимости. */
  PENDING,

  /** Событие успешно передано бизнес-обработчику. */
  PROCESSED,

  /** Обработка события завершилась ошибкой. */
  FAILED,

  /** Событие слишком долго ожидало зависимости. */
  EXPIRED
}
